import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import { Registry } from '../src/registry.js';
import { ResourceControl } from '../src/resource-control.js';
import { createSaveService } from '../src/save-service.js';
import { createProjectMoveService } from '../src/project-move-service.js';
import { startAtlasUiServer } from '../src/ui-server.js';

const field = (html, name) => html.match(new RegExp(`name="${name}" value="([^"]*)"`, 'u'))?.[1];
const binding = html => Object.fromEntries(['expected_revision', 'expected_current_sha256', 'request_key'].map(name => [name, field(html, name)]));
const decode = html => html.replaceAll('&amp;', '&');

test('Applied Move receipt switches to same-Root index, previews selected Markdown, applies repair, reads back and undoes', async t => {
  const root = fs.mkdtempSync(path.resolve('test/.tmp/reference-repair-ui-'));
  const stateDir = path.join(root, 'state'); const workspace = path.join(root, 'workspace');
  const sourceDir = path.join(workspace, 'Source'); const indexDir = path.join(workspace, 'Index');
  fs.mkdirSync(sourceDir, { recursive: true }); fs.mkdirSync(indexDir);
  fs.writeFileSync(path.join(sourceDir, 'doc.md'), '# Source document\n');
  const original = '# Index\n\n[Doc](../Source/doc.md)\n\n[[Source/doc.md]]\n\n[External](https://example.test/Source/doc.md)\n';
  fs.writeFileSync(path.join(indexDir, 'Index.md'), original);
  fs.writeFileSync(path.join(indexDir, 'Unselected.md'), '[Leave](../Source/doc.md)\n');
  fs.writeFileSync(path.join(indexDir, 'NoChange.md'), '# Nothing to repair\n');
  const registry = new Registry({ stateDir });
  const adopted = registry.adoptRoot({ rootPath: workspace, rootType: 'project_workspace', contentPolicy: 'bounded_content' });
  const create = name => { const p = registry.create({ name, currentPath: name }); registry.attachRoot(p.project_id, { rootId: adopted.root_id, relativePath: name, reason: 'Repair fixture.' }); return registry.show(p.project_id).project; };
  const sourceProject = create('Source'); const indexProject = create('Index');
  const resourceControl = new ResourceControl({ stateDir, registry });
  resourceControl.identify({ filePath: path.join(sourceDir, 'doc.md'), project: sourceProject });
  const identify = name => resourceControl.identify({ filePath: path.join(indexDir, name), project: indexProject }).resource_id;
  const indexId = identify('Index.md'); const unselectedId = identify('Unselected.md'); const noChangeId = identify('NoChange.md');
  const saves = createSaveService({ stateDir, resourceControl });
  const moves = createProjectMoveService({ stateDir, registry, resourceControl });
  const caller = { actor: 'user', tool: 'fixture', client_run_id: 'reference-repair-ui' };
  const prepared = moves.prepare({ projectId: sourceProject.id, targetRelativePath: 'Moved', requestKey: 'move-preview', caller });
  const applied = moves.execute(prepared.move_id, { projectId: sourceProject.id, expectedRevision: prepared.revision, expectedDigest: prepared.digest, requestKey: 'move-confirm', caller });
  const server = await startAtlasUiServer({ stateDir, registry, intake: saves.intake, resourceControl, projectRoot: workspace, installationRoot: root });
  t.after(async () => {
    await server.close(); moves.dispose(); saves.dispose(); resourceControl.dispose(); registry.dispose();
    fs.rmSync(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 20 });
  });
  const get = async url => { const response = await fetch(new URL(url, server.workspace_url)); return { status: response.status, html: await response.text() }; };
  const receipt = await get(`/projects/${sourceProject.id}/move/${applied.move_id}`); assert.equal(receipt.status, 200);
  const entryHref = decode(receipt.html.match(/href="([^"]+document-updates\/repair\?[^"]+)"/u)?.[1] ?? ''); assert.ok(entryHref);
  const selection = await get(entryHref); assert.equal(selection.status, 200);
  const switchHref = decode([...selection.html.matchAll(/href="([^"]+)"/gu)].map(match => match[1]).find(href => href.startsWith(`/projects/${indexProject.id}/document-updates/repair?`)) ?? '');
  assert.ok(switchHref, 'Same-Root Project switch must provide index Project entry.');
  const indexSelection = await get(switchHref); assert.equal(indexSelection.status, 200);
  assert.ok(indexSelection.html.includes(indexId)); assert.ok(indexSelection.html.includes(unselectedId));
  assert.doesNotMatch(indexSelection.html, /https:\/\/example.test\/Source\/doc.md/u);
  const csrf = field(indexSelection.html, 'csrf'); assert.ok(csrf);
  const source = Object.fromEntries(['source_kind', 'operation_id', 'source_project_id', 'source_revision', 'source_digest'].map(name => [name, field(indexSelection.html, name)]));
  const post = (url, values, ids = []) => {
    const body = new URLSearchParams({ csrf, ...values }); ids.forEach(id => body.append('resource_id', id));
    return fetch(new URL(url, server.workspace_url), { method: 'POST', redirect: 'manual', headers: { 'content-type': 'application/x-www-form-urlencoded' }, body });
  };
  const repairPath = `/projects/${indexProject.id}/document-updates/repair`;
  assert.equal((await post(repairPath, { ...source, csrf: 'invalid', request_key: 'csrf' }, [indexId])).status, 403);
  assert.equal((await post(repairPath, { ...source, source_revision: '999', request_key: 'stale-source' }, [indexId])).status, 409);
  assert.equal((await post(repairPath, { ...source, request_key: 'none' })).status, 400);
  const preview = await post(repairPath, { ...source, request_key: 'chosen' }, [indexId]);
  assert.equal(preview.status, 303, await preview.clone().text());
  assert.equal(fs.readFileSync(path.join(indexDir, 'Index.md'), 'utf8'), original);
  const updatePath = preview.headers.get('location'); const shown = await get(updatePath); assert.equal(shown.status, 200);
  assert.match(shown.html, /\.\.\/Source\/doc.md/u); assert.match(shown.html, /\.\.\/Moved\/doc.md/u);
  assert.doesNotMatch(shown.html, /value="revise"|textarea name="text"/u);
  const accepted = await post(`${updatePath}/decide`, { ...binding(shown.html), decision: 'accept-suggestion' });
  assert.equal(accepted.status, 303, await accepted.clone().text());
  const acceptedView = await get(updatePath);
  assert.equal((await post(`${updatePath}/execute`, binding(acceptedView.html))).status, 303);
  const text = fs.readFileSync(path.join(indexDir, 'Index.md'), 'utf8');
  assert.match(text, /\[Doc\]\(\.\.\/Moved\/doc.md\)/u); assert.match(text, /\[\[Moved\/doc.md\]\]/u);
  assert.match(text, /https:\/\/example.test\/Source\/doc.md/u);
  assert.equal(fs.readFileSync(path.join(indexDir, 'Unselected.md'), 'utf8'), '[Leave](../Source/doc.md)\n');
  const read = await get(`/projects/${indexProject.id}/resources/read?resource_id=${encodeURIComponent(indexId)}`); assert.equal(read.status, 200); assert.match(read.html, /Moved\/doc.md/u);
  const appliedView = await get(updatePath);
  assert.equal((await post(`${updatePath}/undo`, binding(appliedView.html))).status, 303);
  assert.equal(fs.readFileSync(path.join(indexDir, 'Index.md'), 'utf8'), original);
  const unchanged = await post(repairPath, { ...source, request_key: 'no-change' }, [noChangeId]);
  assert.equal(unchanged.status, 200, await unchanged.clone().text());
  assert.match(await unchanged.text(), /No supported link changes/u);
});
